/* ============================================================
   SELECT-запросы для таблицы inventory
   Назначение:
   Используются для админ-панели, карточек, фильтров и аналитики
============================================================ */

/* ------------------------------------------------------------
   Получить весь инвентарь (полный список)
------------------------------------------------------------ */

SELECT *
FROM inventory
ORDER BY created_at DESC;


/* ------------------------------------------------------------
   Список для админки (только основные поля)
------------------------------------------------------------ */

SELECT
  id,
  stock_no,
  title,
  brand,
  model,
  year,
  price,
  status,
  created_at
FROM inventory
ORDER BY created_at DESC;


/* ------------------------------------------------------------
   Получить одну карточку по ID
------------------------------------------------------------ */

SELECT *
FROM inventory
WHERE id = 1;


/* ------------------------------------------------------------
   Получить карточку по складскому номеру
------------------------------------------------------------ */

SELECT *
FROM inventory
WHERE stock_no = '00002165461232';


/* ------------------------------------------------------------
   Только активные записи
------------------------------------------------------------ */

SELECT
  id,
  stock_no,
  title,
  price
FROM inventory
WHERE status = 'active'
ORDER BY price ASC;


/* ------------------------------------------------------------
   Фильтр по бренду и модели
------------------------------------------------------------ */

SELECT
  id,
  title,
  year,
  mileage,
  price
FROM inventory
WHERE brand = 'Toyota'
  AND model = 'Camry'
ORDER BY year DESC;


/* ------------------------------------------------------------
   Фильтр по диапазону цены
------------------------------------------------------------ */

SELECT
  id,
  title,
  price
FROM inventory
WHERE price BETWEEN 15000 AND 20000
ORDER BY price ASC;


/* ------------------------------------------------------------
   Фильтр по пробегу
------------------------------------------------------------ */

SELECT
  id,
  title,
  mileage
FROM inventory
WHERE mileage <= 80000
ORDER BY mileage ASC;


/* ------------------------------------------------------------
   Поиск по заголовку и краткому описанию
------------------------------------------------------------ */

SELECT
  id,
  title,
  description_short
FROM inventory
WHERE title ILIKE '%camry%'
   OR description_short ILIKE '%camry%';


/* ------------------------------------------------------------
   Расширенный фильтр (форма поиска)
------------------------------------------------------------ */

SELECT
  id,
  title,
  brand,
  model,
  year,
  price
FROM inventory
WHERE status = 'active'
  AND (brand = 'Toyota' OR brand = 'Honda')
  AND year >= 2018
  AND price <= 20000
ORDER BY year DESC, price ASC;


/* ------------------------------------------------------------
   Пагинация для таблицы в админке
------------------------------------------------------------ */

SELECT
  id,
  stock_no,
  title,
  status,
  created_at
FROM inventory
ORDER BY created_at DESC
LIMIT 20 OFFSET 0;


/* ------------------------------------------------------------
   Подсчёт общего количества записей
------------------------------------------------------------ */

SELECT
  COUNT(*) AS total_items
FROM inventory;


/* ------------------------------------------------------------
   Статистика по статусам
------------------------------------------------------------ */

SELECT
  status,
  COUNT(*) AS count
FROM inventory
GROUP BY status;


/* ------------------------------------------------------------
   Минимальная и максимальная цена
------------------------------------------------------------ */

SELECT
  MIN(price) AS min_price,
  MAX(price) AS max_price
FROM inventory
WHERE price IS NOT NULL;


/* ------------------------------------------------------------
   Последние обновлённые записи
------------------------------------------------------------ */

SELECT
  id,
  title,
  updated_at
FROM inventory
ORDER BY updated_at DESC
LIMIT 10;


/* ------------------------------------------------------------
   Черновики (не опубликованные записи)
------------------------------------------------------------ */

SELECT
  id,
  title,
  created_at
FROM inventory
WHERE status = 'draft'
ORDER BY created_at DESC;


/* ------------------------------------------------------------
   Универсальный SELECT под форму фильтров (backend template)
------------------------------------------------------------ */

SELECT
  id,
  title,
  brand,
  model,
  year,
  mileage,
  price
FROM inventory
WHERE 1 = 1
  AND (:status IS NULL OR status = :status)
  AND (:brand IS NULL OR brand = :brand)
  AND (:year_from IS NULL OR year >= :year_from)
  AND (:year_to IS NULL OR year <= :year_to)
  AND (:price_from IS NULL OR price >= :price_from)
  AND (:price_to IS NULL OR price <= :price_to)
ORDER BY created_at DESC;
