/* ============================================================
   Таблица: inventory
   Назначение:
   Хранение объектов инвентаря (авто / товар / объявление)
   Используется в админ-панели и формах редактирования.
============================================================ */

CREATE TABLE inventory (

  /* ============================================================
     Identity — идентификация записи
     ------------------------------------------------------------
     Блок отвечает за уникальность объекта и его жизненный статус
  ============================================================ */

  -- Уникальный идентификатор записи
  -- SERIAL создаёт автоинкрементируемое целое число
  id SERIAL PRIMARY KEY,

  -- Внутренний / складской номер
  -- Используется в UI, CRM, ERP, не должен повторяться
  stock_no VARCHAR(32) NOT NULL UNIQUE,

  -- Статус объекта:
  -- draft     — черновик
  -- active    — активен / опубликован
  -- sold      — продан
  -- archived  — архив
  
  status VARCHAR(20) NOT NULL DEFAULT 'draft',


  /* ============================================================
     General — основные характеристики объекта
     ------------------------------------------------------------
     Базовые поля, которые чаще всего используются в списках
  ============================================================ */

  -- Заголовок объявления / карточки
  -- Отображается в списках и шапке страницы
  title VARCHAR(150) NOT NULL,

  -- Бренд / производитель
  brand VARCHAR(80),

  -- Модель
  model VARCHAR(80),

  -- Год выпуска
  -- Минимальное значение ограничено 1900 годом
  year INTEGER CHECK (year >= 1900),

  -- Общее состояние (строка, без ENUM для простоты)
  -- Например: new, good, used, damaged
  condition VARCHAR(30),

  -- Пробег / наработка
  -- Не может быть отрицательным
  mileage INTEGER CHECK (mileage >= 0),

  -- Единица измерения пробега
  -- km / mi
  mileage_unit VARCHAR(10) NOT NULL DEFAULT 'km',

  -- VIN или серийный номер
  -- Сделан уникальным, но допускает NULL
  vin VARCHAR(20) UNIQUE,


  /* ============================================================
     Description — текстовые описания
     ------------------------------------------------------------
     Используются в карточке товара и SEO
  ============================================================ */

  -- Краткий подзаголовок
  subtitle VARCHAR(200),

  -- Короткое описание (превью)
  description_short TEXT,

  -- Полное описание
  description_full TEXT,


  /* ============================================================
     Pricing — ценовые параметры
     ------------------------------------------------------------
     Все значения защищены от отрицательных чисел
  ============================================================ */

  -- Основная цена
  price NUMERIC(12,2) CHECK (price >= 0),

  -- Валюта (по умолчанию USD)
  currency VARCHAR(10) NOT NULL DEFAULT 'USD',

  -- Скидка
  discount NUMERIC(12,2) CHECK (discount >= 0),

  -- Включён ли налог в цену
  tax_included BOOLEAN NOT NULL DEFAULT FALSE,


  /* ============================================================
     Options / Features — комплектация и особенности
     ------------------------------------------------------------
     Храним текстом (через запятую или JSON строку)
     для упрощения MVP
  ============================================================ */

  -- Опции (например: климат, подогрев, ассистенты)
  options TEXT,

  -- Дополнительные особенности / фичи
  features TEXT,


  /* ============================================================
     Checklist — чек-листы и проверки
     ------------------------------------------------------------
     Используется для предпродажной подготовки
  ============================================================ */

  -- Чек-лист в свободном формате
  checklist TEXT,

  -- Признак завершения чек-листа
  checklist_done BOOLEAN NOT NULL DEFAULT FALSE,


  /* ============================================================
     Keys / Documents — ключи и документы
     ------------------------------------------------------------
     Полезно для автомобилей и техники
  ============================================================ */

  -- Количество ключей
  -- Не может быть отрицательным
  keys_count INTEGER NOT NULL DEFAULT 0 CHECK (keys_count >= 0),

  -- Наличие запасного ключа
  has_spare_key BOOLEAN NOT NULL DEFAULT FALSE,

  -- Документы (ПТС, сервисная книжка и т.д.)
  documents TEXT,


  /* ============================================================
     Disclosures — юридические раскрытия
     ------------------------------------------------------------
     Аварии, ограничения, повреждения
  ============================================================ */

  -- Раскрытия в свободном формате
  disclosures TEXT,

  -- Дополнительные юридические комментарии
  disclosure_notes TEXT,


  /* ============================================================
     Contact / Location — контактные данные
     ------------------------------------------------------------
     Используются для связи и логистики
  ============================================================ */

  -- Контактное лицо
  contact_name VARCHAR(120),

  -- Email для связи
  contact_email VARCHAR(120),

  -- Телефон
  contact_phone VARCHAR(40),

  -- Страна
  country VARCHAR(50),

  -- Город
  city VARCHAR(80),

  -- Адрес
  address VARCHAR(150),


  /* ============================================================
     Meta — служебные поля
     ------------------------------------------------------------
     Используются для сортировки и аудита
  ============================================================ */

  -- Дата создания записи
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Дата последнего обновления
  -- Может обновляться триггером в будущем
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
