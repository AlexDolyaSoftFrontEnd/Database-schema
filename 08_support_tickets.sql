/* ============================================================
   Файл: 08_support_tickets.sql
   Назначение:
   Система обращений пользователей (support / helpdesk)

   COMMIT LOG:
   ------------------------------------------------------------
   [INIT]        Базовая таблица тикетов
   [STATUS]      Жизненный цикл обращения
   [PRIORITY]    Добавлена приоритетность
   [RELATION]    Связь с пользователями
   [AUDIT]       Служебные поля
============================================================ */

CREATE TABLE support_tickets (

  /* ============================================================
     COMMIT: [INIT] — Идентификация тикета
  ============================================================ */

  -- Уникальный ID тикета
  id SERIAL PRIMARY KEY,


  /* ============================================================
     COMMIT: [RELATION] — Пользователь
  ============================================================ */

  -- Пользователь, создавший тикет
  user_id INTEGER NOT NULL,


  /* ============================================================
     COMMIT: [CONTENT] — Содержание обращения
  ============================================================ */

  -- Тема обращения
  subject VARCHAR(150) NOT NULL,

  -- Описание проблемы
  message TEXT NOT NULL,


  /* ============================================================
     COMMIT: [STATUS] — Статус тикета
     ------------------------------------------------------------
     open       — открыт
     in_progress — в работе
     resolved   — решён
     closed     — закрыт
  ============================================================ */

  status VARCHAR(30) NOT NULL DEFAULT 'open',


  /* ============================================================
     COMMIT: [PRIORITY] — Приоритет обработки
  ============================================================ */

  -- low | normal | high | critical
  priority VARCHAR(20) NOT NULL DEFAULT 'normal',


  /* ============================================================
     COMMIT: [AUDIT] — Служебные поля
  ============================================================ */

  -- Дата создания
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Дата закрытия тикета
  closed_at TIMESTAMP
);
