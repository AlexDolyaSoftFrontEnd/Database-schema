/* ============================================================
   Файл: 02_users.sql
   Назначение:
   Хранение пользователей системы (CRM / SaaS / Admin panel)

   История изменений (commit log):
   ------------------------------------------------------------
   [INIT]       Создана базовая таблица пользователей
   [AUTH]       Добавлена поддержка авторизации
   [ROLES]      Реализована ролевая модель
   [SECURITY]   Пароли хранятся только в виде хэшей
   [AUDIT]      Добавлены служебные поля
============================================================ */

CREATE TABLE users (

  /* ============================================================
     COMMIT: [INIT] — Идентификация пользователя
     ------------------------------------------------------------
     Базовые поля для уникального определения пользователя
  ============================================================ */

  -- Уникальный идентификатор пользователя
  id SERIAL PRIMARY KEY,

  -- Email используется как логин
  -- Должен быть уникальным
  email VARCHAR(120) NOT NULL UNIQUE,


  /* ============================================================
     COMMIT: [AUTH] — Авторизация и безопасность
     ------------------------------------------------------------
     Пароль никогда не хранится в открытом виде
  ============================================================ */

  -- Хэш пароля (bcrypt / argon2)
  password_hash TEXT NOT NULL,

  -- Восстановление пароля
  reset_token VARCHAR(120),
  reset_token_expires TIMESTAMP,

  /* ============================================================
     COMMIT: [ROLES] — Ролевая модель
     ------------------------------------------------------------
     Управление доступами в админке
  ============================================================ */

  -- user | admin | manager | moderator
  role VARCHAR(30) NOT NULL DEFAULT 'user',

  -- Активен ли пользователь
  is_active BOOLEAN NOT NULL DEFAULT TRUE,


  /* ============================================================
     COMMIT: [PROFILE] — Профиль пользователя
     ------------------------------------------------------------
     Не участвует в логике авторизации
  ============================================================ */

  first_name VARCHAR(80),
  last_name VARCHAR(80),
  phone VARCHAR(40),
  avatar_url TEXT,


  /* ============================================================
     COMMIT: [AUDIT] — Служебные и системные поля
     ------------------------------------------------------------
     Используются для логирования и аналитики
  ============================================================ */

  -- Дата регистрации
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Последнее обновление профиля
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Последний вход в систему
  last_login TIMESTAMP
);
