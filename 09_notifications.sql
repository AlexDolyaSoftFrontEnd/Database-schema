/* ============================================================
   Файл: 10_notifications.sql
   Назначение:
   Уведомления пользователей (системные, email, UI)

   COMMIT LOG:
   ------------------------------------------------------------
   [INIT]      Создана таблица уведомлений
   [TYPES]     Поддержка разных типов уведомлений
   [READ]      Добавлено состояние прочтения
   [AUDIT]     Служебные поля
============================================================ */

CREATE TABLE notifications (

  /* ============================================================
     COMMIT: [INIT] — Идентификация уведомления
  ============================================================ */

  -- Уникальный идентификатор
  id SERIAL PRIMARY KEY,


  /* ============================================================
     COMMIT: [RELATION] — Пользователь
  ============================================================ */

  -- Получатель уведомления
  user_id INTEGER NOT NULL,


  /* ============================================================
     COMMIT: [TYPES] — Тип уведомления
  ============================================================ */

  -- system | order | payment | support
  type VARCHAR(50) NOT NULL,

  -- Текст уведомления
  message TEXT NOT NULL,


  /* ============================================================
     COMMIT: [READ] — Состояние
  ============================================================ */

  -- Прочитано ли уведомление
  is_read BOOLEAN NOT NULL DEFAULT FALSE,


  /* ============================================================
     COMMIT: [AUDIT] — Служебные поля
  ============================================================ */

  -- Дата создания
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
