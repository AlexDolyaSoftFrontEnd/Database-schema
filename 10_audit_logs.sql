/* ============================================================
   Файл: 11_audit_logs.sql
   Назначение:
   Аудит действий пользователей и системных событий
   (безопасность, аналитика, соответствие требованиям)

   COMMIT LOG:
   ------------------------------------------------------------
   [INIT]       Создан базовый журнал событий
   [SECURITY]   Добавлена фиксация критических действий
   [RELATION]   Связь с пользователями и сущностями
   [META]       Хранение контекста и IP
   [AUDIT]      Подготовка к логированию и аналитике
============================================================ */

CREATE TABLE audit_logs (

  /* ============================================================
     COMMIT: [INIT] — Идентификация события
  ============================================================ */

  -- Уникальный идентификатор записи лога
  id SERIAL PRIMARY KEY,


  /* ============================================================
     COMMIT: [RELATION] — Пользователь / система
     ------------------------------------------------------------
     user_id может быть NULL для системных событий
  ============================================================ */

  -- Пользователь, выполнивший действие
  user_id INTEGER,

  -- Тип инициатора
  -- user | system | api
  actor_type VARCHAR(20) NOT NULL DEFAULT 'user',


  /* ============================================================
     COMMIT: [ACTION] — Действие
     ------------------------------------------------------------
     Фиксируется само событие
  ============================================================ */

  -- Тип действия
  -- create | update | delete | login | logout | export
  action VARCHAR(50) NOT NULL,

  -- Краткое описание действия
  description VARCHAR(255),


  /* ============================================================
     COMMIT: [ENTITY] — Связанная сущность
     ------------------------------------------------------------
     Над чем было выполнено действие
  ============================================================ */

  -- Тип сущности
  -- user | order | payment | inventory | project
  entity_type VARCHAR(50),

  -- ID сущности
  entity_id INTEGER,


  /* ============================================================
     COMMIT: [META] — Контекст и окружение
     ------------------------------------------------------------
     Полезно для безопасности и расследований
  ============================================================ */

  -- IP-адрес инициатора
  ip_address VARCHAR(45),

  -- User-Agent (браузер / клиент)
  user_agent TEXT,

  -- Дополнительные данные (JSON в виде строки)
  metadata TEXT,


  /* ============================================================
     COMMIT: [AUDIT] — Служебные поля
  ============================================================ */

  -- Дата и время события
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
