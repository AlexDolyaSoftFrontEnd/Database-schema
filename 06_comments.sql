/* ============================================================
   Файл: 06_comments.sql
   Назначение:
   Хранение комментариев к статьям / объектам / сущностям системы

   COMMIT LOG:
   ------------------------------------------------------------
   [INIT]      Создана таблица комментариев
   [RELATION]  Добавлены связи с пользователями и сущностями
   [MODERATE]  Реализована модерация
   [AUDIT]     Добавлены служебные поля
============================================================ */

CREATE TABLE comments (

  /* ============================================================
     COMMIT: [INIT] — Идентификация комментария
  ============================================================ */

  -- Уникальный идентификатор комментария
  id SERIAL PRIMARY KEY,


  /* ============================================================
     COMMIT: [RELATION] — Связи
     ------------------------------------------------------------
     Комментарий может принадлежать статье, товару или проекту
  ============================================================ */

  -- ID сущности (post / product / project)
  entity_id INTEGER NOT NULL,

  -- Тип сущности
  -- post | product | project
  entity_type VARCHAR(30) NOT NULL,

  -- Автор комментария (может быть NULL для гостей)
  user_id INTEGER,


  /* ============================================================
     COMMIT: [CONTENT] — Контент комментария
  ============================================================ */

  -- Текст комментария
  message TEXT NOT NULL,


  /* ============================================================
     COMMIT: [MODERATE] — Модерация
  ============================================================ */

  -- Одобрен ли комментарий
  is_approved BOOLEAN NOT NULL DEFAULT FALSE,

  -- Скрыт ли комментарий
  is_hidden BOOLEAN NOT NULL DEFAULT FALSE,


  /* ============================================================
     COMMIT: [AUDIT] — Служебные поля
  ============================================================ */

  -- Дата создания
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- Дата последнего изменения
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
